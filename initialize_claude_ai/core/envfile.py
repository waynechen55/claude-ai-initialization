"""Persistence of discovered paths and settings as environment variables.

Phase 1 records where every binary actually landed; phases 2-4 (and any later
shell session) read those values back instead of re-guessing.  Three artefacts
are produced, all under the state directory:

* ``env.json`` -- machine-readable, the source of truth for later phases
* ``env.sh``   -- ``export`` lines for POSIX shells (``source`` it)
* ``env.fish`` -- ``set -gx`` lines, written only when fish is present

Values are also pushed into ``os.environ`` for the current process so the very
next phase sees them without a reload.  Nothing marked secret is ever written to
disk here -- only paths, versions, ids and regions.
"""

from __future__ import annotations

import json
import os
import re
import shlex
import shutil
from dataclasses import dataclass, field
from datetime import datetime, timezone
from pathlib import Path
from typing import Any, Iterator, Mapping

from . import redact
from .fileio import write_private
from .logging_setup import get_logger

log = get_logger("envstore")

_SAFE_NAME = re.compile(r"^[A-Za-z_][A-Za-z0-9_]*$")

_HEADER = (
    "# Generated by initialize-claude-ai -- do not edit by hand.\n"
    "# Regenerate with: initialize-claude-ai run --phases 1\n"
    "# Source this file to expose the discovered Claude environment:\n"
    "#   source {path}\n"
)


@dataclass
class EnvStore:
    """Collects, persists and re-loads the environment produced by the phases."""

    state_dir: Path
    prefix: str = "INITIALIZE_CLAUDE_AI_"
    values: dict[str, str] = field(default_factory=dict)
    #: Names that must be exported verbatim (no prefix) because a third-party
    #: tool reads them -- e.g. ANTHROPIC_VERTEX_PROJECT_ID, CLOUD_ML_REGION.
    passthrough: set[str] = field(default_factory=set)
    dry_run: bool = False
    _dirty: bool = field(default=False, repr=False)

    # -- paths -----------------------------------------------------------------

    @property
    def json_path(self) -> Path:
        return self.state_dir / "env.json"

    @property
    def sh_path(self) -> Path:
        return self.state_dir / "env.sh"

    @property
    def fish_path(self) -> Path:
        return self.state_dir / "env.fish"

    # -- mutation --------------------------------------------------------------

    def qualify(self, name: str) -> str:
        """Return the exported variable name for ``name``."""
        if name in self.passthrough or name.startswith(self.prefix):
            return name
        return f"{self.prefix}{name}"

    def set(self, name: str, value: Any, *, passthrough: bool = False, apply: bool = True) -> str:
        """Record a variable. Returns the exported name."""
        if value in (None, ""):
            return ""
        if passthrough:
            self.passthrough.add(name)
        key = self.qualify(name)
        if not _SAFE_NAME.match(key):
            log.warning("skipping unsafe environment variable name %r", key)
            return ""
        text = str(value)
        if self.values.get(key) != text:
            self.values[key] = text
            self._dirty = True
        if apply:
            os.environ[key] = text
        return key

    def set_binary(self, component: str, path: str | os.PathLike[str] | None) -> str:
        """Record the resolved path of a binary as ``<PREFIX>BIN_<COMPONENT>``."""
        if not path:
            return ""
        token = re.sub(r"[^A-Za-z0-9]+", "_", component).strip("_").upper()
        return self.set(f"BIN_{token}", str(path))

    def set_bin_dir(self, component: str, directory: str | os.PathLike[str] | None) -> str:
        """Record a directory a component installs programs into as ``<PREFIX>BINDIR_<COMPONENT>``.

        Separate from ``BIN_``, whose *parent* directory is what goes on PATH:
        this is a directory already -- ``$GOPATH/bin`` -- and is used as is.
        """
        if not directory:
            return ""
        token = re.sub(r"[^A-Za-z0-9]+", "_", component).strip("_").upper()
        return self.set(f"BINDIR_{token}", str(directory))

    def set_version(self, component: str, version: str | None) -> str:
        if not version:
            return ""
        token = re.sub(r"[^A-Za-z0-9]+", "_", component).strip("_").upper()
        return self.set(f"VERSION_{token}", version)

    def update(self, mapping: Mapping[str, Any], *, passthrough: bool = False) -> None:
        for name, value in mapping.items():
            self.set(name, value, passthrough=passthrough)

    def unset(self, name: str) -> str:
        """Forget a variable this run no longer stands behind.

        These files state what the environment *should* be; they are not a log
        of everything ever written to them. A ``CLAUDE_CODE_USE_VERTEX`` left
        over from an earlier run would keep routing Claude Code through a
        backend the operator has since switched away from -- and would do it
        from a file they never edited, which is the hardest kind of setting to
        find. Returns the exported name that was dropped, or "" if there was
        nothing to drop.
        """
        key = self.qualify(name)
        if key not in self.values:
            return ""
        del self.values[key]
        self.passthrough.discard(name)
        self._dirty = True
        os.environ.pop(key, None)
        return key

    def get(self, name: str, default: str = "") -> str:
        return self.values.get(self.qualify(name), default)

    def binary(self, component: str) -> str:
        token = re.sub(r"[^A-Za-z0-9]+", "_", component).strip("_").upper()
        return self.get(f"BIN_{token}")

    def bin_dirs(self) -> list[str]:
        """Directories containing every recorded binary, and every recorded bin dir, for PATH assembly."""
        dirs: list[str] = []
        for key, value in self.values.items():
            if key.startswith(f"{self.prefix}BIN_"):
                directory = str(Path(value).parent)
            elif key.startswith(f"{self.prefix}BINDIR_"):
                directory = str(value)
            else:
                continue
            if directory and directory not in dirs:
                dirs.append(directory)
        return dirs

    def __iter__(self) -> Iterator[tuple[str, str]]:
        return iter(sorted(self.values.items()))

    def __len__(self) -> int:
        return len(self.values)

    # -- persistence -----------------------------------------------------------

    def load(self) -> "EnvStore":
        """Re-load a previously written store (so phases can run standalone)."""
        if not self.json_path.is_file():
            return self
        try:
            payload = json.loads(self.json_path.read_text(encoding="utf-8"))
        except (OSError, json.JSONDecodeError) as exc:
            log.warning("cannot read %s: %s", self.json_path, exc)
            return self
        stored = payload.get("variables", {})
        if isinstance(stored, Mapping):
            for key, value in stored.items():
                if isinstance(key, str) and _SAFE_NAME.match(key):
                    self.values.setdefault(key, str(value))
        passthrough = payload.get("passthrough", [])
        if isinstance(passthrough, list):
            self.passthrough.update(str(p) for p in passthrough)
        log.debug("loaded %d variables from %s", len(stored), self.json_path)
        return self

    def apply(self) -> None:
        """Push every recorded value into the current process environment."""
        for key, value in self.values.items():
            os.environ[key] = value
        bin_dirs = [d for d in self.bin_dirs() if d not in os.environ.get("PATH", "").split(os.pathsep)]
        if bin_dirs:
            os.environ["PATH"] = os.pathsep.join(bin_dirs + [os.environ.get("PATH", "")])

    def save(self, *, force: bool = False) -> list[Path]:
        """Write env.json / env.sh (+ env.fish). Returns the paths written."""
        if not self.values or (not self._dirty and not force):
            return []
        if self.dry_run:
            log.info("[dry-run] would write %d variables to %s", len(self.values), self.state_dir)
            return []
        written: list[Path] = []
        try:
            self.state_dir.mkdir(parents=True, exist_ok=True)
        except OSError as exc:
            log.error("cannot create state directory %s: %s", self.state_dir, exc)
            return []

        payload = {
            "generated_at": datetime.now(timezone.utc).isoformat(timespec="seconds"),
            "prefix": self.prefix,
            "passthrough": sorted(self.passthrough),
            "variables": dict(sorted(self.values.items())),
        }
        written.append(self._write(self.json_path, json.dumps(payload, indent=2) + "\n"))

        lines = [_HEADER.format(path=self.sh_path)]
        for key, value in sorted(self.values.items()):
            lines.append(f"export {key}={shlex.quote(value)}")
        bin_dirs = self.bin_dirs()
        if bin_dirs:
            joined = ":".join(shlex.quote(d) for d in bin_dirs)
            lines.append("")
            lines.append("# Ensure discovered binaries are reachable")
            lines.append(f'case ":$PATH:" in *":{bin_dirs[0]}:"*) ;; *) PATH="{joined}:$PATH" ;; esac')
            lines.append("export PATH")
        written.append(self._write(self.sh_path, "\n".join(lines) + "\n"))

        # On PATH, not at one fixed location: fish from Homebrew or /usr/local
        # is as much fish as /usr/bin/fish, and its users need the file too.
        if os.environ.get("SHELL", "").endswith("fish") or shutil.which("fish"):
            fish = [_HEADER.format(path=self.fish_path)]
            fish.extend(f"set -gx {key} {shlex.quote(value)}" for key, value in sorted(self.values.items()))
            fish.extend(f"fish_add_path {shlex.quote(d)}" for d in bin_dirs)
            written.append(self._write(self.fish_path, "\n".join(fish) + "\n"))

        self._dirty = False
        log.info("wrote %d environment variables to %s", len(self.values), self.state_dir)
        return [p for p in written if p]

    def _write(self, path: Path, content: str) -> Path | None:
        try:
            return write_private(path, content)
        except OSError as exc:
            log.error("cannot write %s: %s", path, exc)
            return None

    def summary(self) -> dict[str, str]:
        """Redacted view suitable for a report or the console."""
        return {key: redact.redact(value) for key, value in sorted(self.values.items())}

    def shell_hint(self) -> str:
        return f"source {self.sh_path}"

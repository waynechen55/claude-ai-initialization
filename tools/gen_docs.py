#!/usr/bin/env python3
"""Generate the reference documents from their sources, or check they are current.

* ``docs/cli-reference.md`` -- the full ``--help`` of every command, from the parser.
* ``docs/config-reference.md`` -- every setting in ``initialize_claude_ai/data/*.toml``
  with its packaged default and the comment written above it.

Usage::

    python tools/gen_docs.py           # write both files
    python tools/gen_docs.py --check   # exit 1 when either is out of date (CI, tests)

Generated text is independent of the machine: help is rendered at a fixed width,
without colour. argparse lays help out differently before Python 3.13, so the
exact CLI comparison runs on the docs job's Python (3.13); the test suite checks
on every version that each option is documented.
"""

from __future__ import annotations

import argparse
import os
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DOCS = ROOT / "docs"
DATA = ROOT / "initialize_claude_ai" / "data"
WIDTH = "100"
NOTICE = "<!-- Generated by tools/gen_docs.py; do not edit by hand. Regenerate with `make docs`. -->"
TABLE = re.compile(r"^\s*(\[\[?)\s*([^\]]+?)\s*\]\]?\s*(?:#.*)?$")
KEY = re.compile(r"^([A-Za-z0-9_\-]+|\"[^\"]+\")\s*=\s*(.*)$")


def render_cli() -> str:
    saved = {k: os.environ.get(k) for k in ("COLUMNS", "LINES", "NO_COLOR", "PYTHON_COLORS", "FORCE_COLOR")}
    os.environ.update({"COLUMNS": WIDTH, "LINES": "50", "NO_COLOR": "1", "PYTHON_COLORS": "0"})
    os.environ.pop("FORCE_COLOR", None)
    try:
        sys.path.insert(0, str(ROOT))
        from initialize_claude_ai import cli

        text = cli.format_full_help(cli.build_parser())
    finally:
        for key, value in saved.items():
            if value is None:
                os.environ.pop(key, None)
            else:
                os.environ[key] = value
    return "\n".join(
        [
            "# Command-line reference",
            "",
            NOTICE,
            "",
            "The complete `initialize-claude-ai --help`. For what the options are for and how they",
            "combine, see [Usage](usage.md) and the phase guides.",
            "",
            "```text",
            text.rstrip(),
            "```",
            "",
        ]
    )


def _balance(text: str) -> int:
    """Open minus closed brackets and braces outside strings (``"…"``, ``'…'``, triple-quoted) and comments."""
    depth, quote, index = 0, "", 0
    while index < len(text):
        if quote:
            if quote == '"' and text[index] == "\\":
                index += 2
                continue
            if text.startswith(quote, index):
                index += len(quote)
                quote = ""
                continue
        else:
            triple = text[index : index + 3]
            if triple in ('"""', "'''"):
                quote, index = triple, index + 3
                continue
            char = text[index]
            if char in "\"'":
                quote = char
            elif char == "#":
                break
            elif char in "[{":
                depth += 1
            elif char in "]}":
                depth -= 1
        index += 1
    return depth


def _value_summary(first: str, more: bool) -> str:
    value = first.split(" #", 1)[0].strip() if not first.strip().startswith(('"', "'")) else first.strip()
    if more:
        value = value.rstrip() + " …"
    if len(value) > 70:
        value = value[:67].rstrip() + "…"
    return "`" + value.replace("`", "'").replace("|", "\\|") + "`"


def render_config() -> str:
    out = [
        "# Configuration reference",
        "",
        NOTICE,
        "",
        "Every setting the program reads, with its packaged default and the comment written beside",
        "it in `initialize_claude_ai/data/`. Override any of them as described in",
        "[Configuration](configuration.md): a config file, `INITIALIZE_CLAUDE_AI_<SECTION>__<KEY>`, or",
        "`--set section.key=value`. Defaults spanning several lines are shortened here (…);",
        "the TOML file is the authority.",
        "",
    ]
    files = sorted(DATA.glob("*.toml"))
    out.append("Files: " + " · ".join(f"[`{p.name}`](#{p.stem.lower()})" for p in files))
    out.append("")
    for path in files:
        out += [
            f"## {path.stem}",
            "",
            f"Source: [`initialize_claude_ai/data/{path.name}`](../initialize_claude_ai/data/{path.name})",
            "",
        ]
        table, rows, comment, depth = "", [], [], 0
        lines = path.read_text(encoding="utf-8").splitlines()

        def flush() -> None:
            if rows:
                out.extend([f"### `[{table}]`", "", "| Key | Default | Description |", "|---|---|---|", *rows, ""])

        for line in lines:
            stripped = line.strip()
            if depth:
                depth = max(0, depth + _balance(stripped))
                continue
            if stripped.startswith("#"):
                text = stripped.lstrip("#").strip()
                if text and not set(text) <= set("#=-"):
                    comment.append(text)
                continue
            if not stripped:
                comment = []
                continue
            header = TABLE.match(line)
            if header and not KEY.match(stripped):
                flush()
                table, rows, comment = header.group(2), [], []
                continue
            found = KEY.match(stripped)
            if not found or line[:1].isspace():
                continue
            value = found.group(2)
            depth = max(0, _balance(value))
            description = " ".join(comment).replace("|", "\\|")
            rows.append(f"| `{found.group(1)}` | {_value_summary(value, depth > 0)} | {description} |")
            comment = []
        flush()
    return "\n".join(out).rstrip() + "\n"


TARGETS = {"cli-reference.md": render_cli, "config-reference.md": render_config}


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--check", action="store_true", help="fail when a generated file is out of date")
    args = parser.parse_args(argv)
    stale = []
    for name, render in TARGETS.items():
        path = DOCS / name
        text = render()
        current = path.read_text(encoding="utf-8") if path.exists() else ""
        if text == current:
            continue
        if args.check:
            stale.append(name)
        else:
            DOCS.mkdir(exist_ok=True)
            path.write_text(text, encoding="utf-8")
            print(f"wrote docs/{name}")
    for name in stale:
        print(f"::error::docs/{name} is out of date; run `python tools/gen_docs.py` and commit the result")
    return 1 if stale else 0


if __name__ == "__main__":
    sys.exit(main())
